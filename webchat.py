"""Web chat API — powers the embeddable widget."""
import logging
from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse
from pydantic import BaseModel
from db import get_company_by_api_key
from nilechat import reply as nilechat_reply

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/chat", tags=["webchat"])


class ChatMessage(BaseModel):
    api_key: str
    session_id: str   # generated by widget (UUID stored in sessionStorage)
    message: str
    name: str | None = None


@router.post("/message")
async def chat_message(body: ChatMessage):
    company = await get_company_by_api_key(body.api_key)
    if not company:
        raise HTTPException(status_code=401, detail="Invalid API key")

    phone = f"web_{body.session_id}"

    try:
        bot_reply = await nilechat_reply(
            user_text=body.message,
            phone=phone,
            platform="web",
            name=body.name,
            company_id=company["id"],
            company_name=company["name"],
            knowledge_base=company["knowledge_base"],
        )
    except Exception as e:
        logger.exception(f"Web chat error: {e}")
        raise HTTPException(status_code=500, detail="Bot error")

    return {"reply": bot_reply}


@router.get("/welcome")
async def get_welcome(api_key: str):
    company = await get_company_by_api_key(api_key)
    if not company:
        raise HTTPException(status_code=401, detail="Invalid API key")
    return {
        "company": company["name"],
        "welcome": company["welcome_message"] or "أهلاً! كيف أقدر أساعدك؟",
    }
